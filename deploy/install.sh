#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
#  Nuqa — one-command installer for a fresh Ubuntu / Debian VPS
#
#    curl -fsSL https://raw.githubusercontent.com/FahadEsam91/laundry/main/deploy/install.sh | sudo bash
#
#  Installs Docker, downloads the app, generates secrets, starts PostgreSQL + the app +
#  Caddy (automatic HTTPS), opens the firewall and schedules daily database backups.
#  Re-running it is safe: an existing .env is kept and the app is updated.
#  Any prompt can be pre-answered with an environment variable of the same name
#  (DOMAIN, ADMIN_PHONE, ADMIN_NAME, MODE, TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN, TWILIO_FROM).
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

REPO=${REPO:-https://github.com/FahadEsam91/laundry.git}
BRANCH=${BRANCH:-main}
DIR=${DIR:-/opt/nuqa}

say()  { printf '\n\033[1;34m▶ %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m✓ %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m! %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m✗ %s\033[0m\n' "$*"; exit 1; }
ask()  { # ask VAR "Question" "default"
  local var=$1 q=$2 def=${3:-} ans=""
  if [ -n "${!var:-}" ]; then return; fi
  if (exec </dev/tty) 2>/dev/null; then read -rp "$q${def:+ [$def]}: " ans </dev/tty || true; fi
  printf -v "$var" '%s' "${ans:-$def}"
}
b64url() { base64 | tr -d '=\n' | tr '/+' '_-'; }

# VAPID (web push) key pair with plain openssl: P-256 private scalar + uncompressed public point
gen_vapid() {
  local k; k=$(mktemp)
  openssl ecparam -name prime256v1 -genkey -noout -out "$k" 2>/dev/null
  VAPID_PRIVATE_KEY=$(openssl ec -in "$k" -outform DER 2>/dev/null | tail -c +8 | head -c 32 | b64url)
  VAPID_PUBLIC_KEY=$(openssl ec -in "$k" -pubout -outform DER 2>/dev/null | tail -c 65 | b64url)
  rm -f "$k"
}

write_env() {
  local ip default_domain
  ip=$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')
  default_domain="$(echo "$ip" | tr . -).sslip.io"
  echo
  echo "No domain yet? Press Enter to use a free automatic address for this server: $default_domain"
  ask DOMAIN "Domain" "$default_domain"
  ask ADMIN_PHONE "Super-admin phone number (international, e.g. +9647701234567)" ""
  [ -n "$ADMIN_PHONE" ] || die "An admin phone number is required"
  ask ADMIN_NAME "Super-admin name" "Admin"
  ask MODE "Mode: 1 = production (empty, real customers)  2 = demo (sample data)" "1"
  echo
  echo "SMS for login codes (Twilio). Press Enter to skip for now — codes will then only appear in the server log."
  ask TWILIO_ACCOUNT_SID "Twilio Account SID" ""
  if [ -n "$TWILIO_ACCOUNT_SID" ]; then
    ask TWILIO_AUTH_TOKEN "Twilio Auth Token" ""
    ask TWILIO_FROM "Twilio sender (+1… number or MG… messaging service)" ""
  fi
  gen_vapid
  umask 077
  cat > .env <<ENV
# Generated by deploy/install.sh on $(date -u +%F). Keep this file private.
DOMAIN=$DOMAIN
SESSION_SECRET=$(openssl rand -base64 48 | tr -d '\n')
POSTGRES_PASSWORD=$(openssl rand -hex 24)
NUQA_DEMO=$([ "$MODE" = "2" ] && echo 1 || echo 0)
ADMIN_PHONE=$ADMIN_PHONE
ADMIN_NAME=$ADMIN_NAME
SMS_PROVIDER=$([ -n "$TWILIO_ACCOUNT_SID" ] && echo twilio || echo console)
TWILIO_ACCOUNT_SID=$TWILIO_ACCOUNT_SID
TWILIO_AUTH_TOKEN=${TWILIO_AUTH_TOKEN:-}
TWILIO_FROM=${TWILIO_FROM:-}
VAPID_PUBLIC_KEY=$VAPID_PUBLIC_KEY
VAPID_PRIVATE_KEY=$VAPID_PRIVATE_KEY
VAPID_SUBJECT=https://$DOMAIN
# REVIEW_LOGINS=+9647000000001:482913     # App Store / Play reviewer logins (see mobile/README.md)
ENV
  chmod 600 .env
  ok ".env created (secrets generated)"
}

[ "$(id -u)" = 0 ] || die "Please run as root:  sudo bash install.sh"

if [ "${NUQA_SKIP_SYSTEM:-0}" != 1 ]; then
  say "Installing system packages"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq && apt-get install -y -qq git curl openssl ufw ca-certificates >/dev/null
  if ! command -v docker >/dev/null; then
    say "Installing Docker"
    curl -fsSL https://get.docker.com | sh >/dev/null
  fi
  docker compose version >/dev/null 2>&1 || die "Docker Compose plugin missing (apt-get install docker-compose-plugin)"
  ok "Docker $(docker --version | awk '{print $3}' | tr -d ,)"

  for port in 80 443; do
    if ss -ltnH "( sport = :$port )" 2>/dev/null | grep -q . && ! docker ps --format '{{.Ports}}' | grep -q ":$port->"; then
      warn "Port $port is already used by another program (e.g. nginx/apache). Stop it first: systemctl stop nginx apache2"
    fi
  done
fi

say "Downloading Nuqa into $DIR"
if [ -d "$DIR/.git" ]; then git -C "$DIR" fetch -q origin "$BRANCH" && git -C "$DIR" checkout -q "$BRANCH" && git -C "$DIR" pull -q --ff-only origin "$BRANCH"
else git clone -q -b "$BRANCH" "$REPO" "$DIR"; fi
cd "$DIR"
ok "Code at $(git rev-parse --short HEAD)"

if [ -f .env ]; then ok "Keeping existing .env"; else say "Configuration"; write_env; fi
set -a; . ./.env; set +a

if [ "${NUQA_SKIP_SYSTEM:-0}" != 1 ]; then
  say "Firewall"
  ssh_port=$(echo "${SSH_CONNECTION:-x x x 22}" | awk '{print $4}')
  ufw allow "${ssh_port:-22}/tcp" >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null
  ufw --force enable >/dev/null && ok "Open ports: ${ssh_port:-22} (SSH), 80, 443"

  say "Building and starting (first time takes a few minutes)"
  docker compose up -d --build
  docker image prune -f >/dev/null || true

  say "Daily backups at 03:00"
  mkdir -p backups
  (crontab -l 2>/dev/null | grep -v 'deploy/backup.sh'; echo "0 3 * * * $DIR/deploy/backup.sh >> $DIR/backups/backup.log 2>&1") | crontab -
  ok "Backups → $DIR/backups (keep 14 days; copy them off the server too)"

  say "Waiting for https://$DOMAIN (certificate is issued automatically)"
  for _ in $(seq 1 60); do
    if curl -fsS --max-time 5 "https://$DOMAIN/api/health" >/dev/null 2>&1; then ok "Online!"; break; fi
    sleep 5
  done
fi

cat <<DONE

────────────────────────────────────────────────────────────
  Nuqa is installed.

  Customer app : https://$DOMAIN
  Admin        : https://$DOMAIN/admin   (sign in with $ADMIN_PHONE)
  Laundry panel: https://$DOMAIN/partner
  Health       : https://$DOMAIN/api/health

  Mobile apps  : set EXPO_PUBLIC_API_URL=https://$DOMAIN in mobile/eas.json
DONE
if [ "${SMS_PROVIDER:-console}" = console ]; then cat <<DONE

  ⚠ SMS is not configured: login codes are written to the server log only.
     Read your code with:  cd $DIR && docker compose logs app | grep '\[sms\]' | tail -3
     Real customers can't sign in until you add Twilio to $DIR/.env and run deploy/update.sh
DONE
fi
cat <<DONE

  Update later : sudo bash $DIR/deploy/update.sh
  Logs         : cd $DIR && docker compose logs -f app
────────────────────────────────────────────────────────────
DONE
