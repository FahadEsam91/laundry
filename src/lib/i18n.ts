export type TKey = keyof typeof D;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  const entry = D[key];
  let s: string = entry ? entry[lang === "ar" ? 0 : 1] : String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Pick localized field: L(obj, 'name') → obj.name_ar | obj.name_en */
export function pickLang(lang: Lang, obj: any, field: string): string {
  if (!obj) return "";
  return obj[`${field}_${lang}`] ?? obj[`${field}_en`] ?? obj[`${field}_ar`] ?? "";
}
